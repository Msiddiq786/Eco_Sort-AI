import { useEffect, useState } from 'react'
import { BarChart3, AlertTriangle } from 'lucide-react'
import type { ModelMetrics, TrainLogEntry } from '@/types'
import api from '@/services/api'
import MetricsOverview from '@/components/performance/MetricsOverview'
import ConfusionMatrixView from '@/components/performance/ConfusionMatrixView'
import LossChart from '@/components/performance/LossChart'

export default function PerformancePage() {
  const [metrics, setMetrics] = useState<ModelMetrics | null>(null)
  const [trainLog, setTrainLog] = useState<TrainLogEntry[] | null>(null)
  const [loading, setLoading] = useState(true)

  useEffect(() => {
    // Both endpoints return 404 when evaluation/training hasn't been run yet.
    Promise.allSettled([
      api.get<ModelMetrics>('/metrics').then(r => r.data),
      api.get<TrainLogEntry[]>('/train-log').then(r => r.data),
    ]).then(([metricsResult, logResult]) => {
      if (metricsResult.status === 'fulfilled') setMetrics(metricsResult.value)
      if (logResult.status === 'fulfilled') setTrainLog(logResult.value)
      setLoading(false)
    })
  }, [])

  if (loading) {
    return <div className="flex items-center justify-center h-64 text-muted-foreground">Loading…</div>
  }

  const notEvaluated = !metrics && !trainLog

  return (
    <div className="space-y-6">
      <div>
        <h1 className="text-2xl font-bold flex items-center gap-2">
          <BarChart3 className="h-6 w-6 text-primary" />
          Model Performance
        </h1>
        <p className="text-muted-foreground text-sm mt-1">
          Metrics generated by <code>backend/evaluation/evaluate_model.py</code> after training.
        </p>
      </div>

      {notEvaluated && (
        <div className="rounded-md border border-yellow-400/50 bg-yellow-50 dark:bg-yellow-900/20 px-4 py-4 flex gap-3 items-start">
          <AlertTriangle className="h-5 w-5 text-yellow-500 mt-0.5 shrink-0" />
          <div className="text-sm">
            <p className="font-semibold text-yellow-700 dark:text-yellow-400">Model not evaluated yet</p>
            <p className="text-yellow-600 dark:text-yellow-300 mt-1">
              Run the training and evaluation pipeline to see real metrics:
            </p>
            <pre className="mt-2 text-xs bg-yellow-100 dark:bg-yellow-900/40 rounded p-2 overflow-x-auto">
              python backend/training/prepare_dataset.py{'\n'}
              python backend/training/train_vit.py{'\n'}
              python backend/evaluation/evaluate_model.py
            </pre>
          </div>
        </div>
      )}

      {metrics && <MetricsOverview metrics={metrics} />}
      {metrics && <ConfusionMatrixView metrics={metrics} />}
      {trainLog && <LossChart log={trainLog} />}
    </div>
  )
}
