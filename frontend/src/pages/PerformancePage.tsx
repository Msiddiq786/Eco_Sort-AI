import { useEffect, useState } from 'react'
import { BarChart3, Terminal } from 'lucide-react'
import type { ModelMetrics, TrainLogEntry } from '@/types'
import api from '@/services/api'
import PageHeader from '@/components/ui/PageHeader'
import StatusBanner from '@/components/ui/StatusBanner'
import MetricsOverview from '@/components/performance/MetricsOverview'
import ConfusionMatrixView from '@/components/performance/ConfusionMatrixView'
import LossChart from '@/components/performance/LossChart'

export default function PerformancePage() {
  const [metrics, setMetrics] = useState<ModelMetrics | null>(null)
  const [trainLog, setTrainLog] = useState<TrainLogEntry[] | null>(null)
  const [loading, setLoading] = useState(true)

  useEffect(() => {
    Promise.allSettled([
      api.get<ModelMetrics>('/metrics').then(r => r.data),
      api.get<TrainLogEntry[]>('/train-log').then(r => r.data),
    ]).then(([metricsResult, logResult]) => {
      if (metricsResult.status === 'fulfilled') setMetrics(metricsResult.value)
      if (logResult.status === 'fulfilled') setTrainLog(logResult.value)
      setLoading(false)
    })
  }, [])

  if (loading) {
    return (
      <div className="space-y-6 pb-8">
        <div className="skeleton h-20 w-full rounded-2xl" />
        <div className="grid grid-cols-2 md:grid-cols-4 gap-4">
          {[1, 2, 3, 4].map((n) => (
            <div key={n} className="skeleton h-24 rounded-2xl" />
          ))}
        </div>
        <div className="skeleton h-64 rounded-2xl" />
      </div>
    )
  }

  const notEvaluated = !metrics && !trainLog

  return (
    <div className="space-y-6 pb-10">
      <PageHeader
        eyebrow="Evaluation Benchmarks"
        eyebrowIcon={BarChart3}
        icon={BarChart3}
        title="Model Performance"
        subtitle="Held-out test set metrics, confusion matrix heatmap, and training loss/accuracy progression generated by the Vision Transformer evaluation pipeline."
      />

      {notEvaluated && (
        <StatusBanner variant="warning" title="Model Not Evaluated Yet">
          <p>
            Run the training and evaluation scripts to generate live benchmark artifacts served by{' '}
            <code className="px-1.5 py-0.5 rounded bg-amber-100/80 font-mono text-[11px]">/api/metrics</code>{' '}
            and{' '}
            <code className="px-1.5 py-0.5 rounded bg-amber-100/80 font-mono text-[11px]">/api/train-log</code>:
          </p>
          <pre className="mt-2.5 flex items-center gap-2 text-xs bg-white/80 border border-amber-200 rounded-xl p-3 font-mono text-slate-800 overflow-x-auto">
            <Terminal className="h-4 w-4 text-amber-600 shrink-0 self-start mt-0.5" />
            <span>
              python backend/training/prepare_dataset.py{'\n'}
              python backend/training/train_vit.py{'\n'}
              python backend/evaluation/evaluate_model.py
            </span>
          </pre>
        </StatusBanner>
      )}

      {metrics && <MetricsOverview metrics={metrics} />}
      {metrics && <ConfusionMatrixView metrics={metrics} />}
      {trainLog && <LossChart log={trainLog} />}
    </div>
  )
}
